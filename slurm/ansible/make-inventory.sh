#!/usr/bin/env bash
# Writes ansible/inventory.ini from `terraform output instances`, so the IPs are
# always the current ones. Called by `make inventory` (and before every Ansible run).
#   slurm-master -> group [master]
#   all others   -> group [nodes]
set -euo pipefail
cd "$(dirname "$0")"

json=$(terraform -chdir=../terraform output -json instances)

{
  echo "# Generated by 'make inventory' from the Terraform outputs. Do not edit by hand."
  echo "[master]"
  jq -r 'to_entries[] | select(.key == "slurm-master") | "\(.key) ansible_host=\(.value.private_ip)"' <<<"$json"
  echo
  echo "[nodes]"
  jq -r 'to_entries[] | select(.key != "slurm-master") | "\(.key) ansible_host=\(.value.private_ip)"' <<<"$json"
} > inventory.ini

cat inventory.ini
